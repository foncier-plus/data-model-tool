export const LANGUAGES = ['fr', 'en']

export function translate(language, key, vars) {
  const dictionary = dictionaries[language] ?? dictionaries.fr
  const template = dictionary[key] ?? dictionaries.fr[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  )
}

export function pluralKey(language, base, count) {
  return count > 1 ? `${base}.many` : `${base}.one`
}

export function useTranslation() {
  const language = useProjectStore((state) => state.language)
  return {
    language,
    t: (key, vars) => translate(language, key, vars),
  }
}
